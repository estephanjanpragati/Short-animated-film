# Burned-in caption chunks for Hindi reels: words.json + lines.txt -> captions.ts
# A chunk breaks after punctuation (। ! ? , : …) or at 3 words / 18 characters. Each chunk: [first word, last word] indices into WORDS.
# usage: captions_ts.py words.json lines.txt captions.ts
import json, re, sys
W = json.load(open(sys.argv[1])); L = [l for l in open(sys.argv[2], encoding="utf8").read().splitlines() if l.strip()]
toks = [t for l in L for t in l.split() if re.search(r"\w", t)]
assert len(toks) == len(W), (len(toks), len(W))
chunks, cur, chars = [], [], 0
for i, t in enumerate(toks):
    cur.append(i); chars += len(t)
    end = re.search(r"[।!?,:…]$", t) or len(cur) >= 3 or chars >= 18
    if i + 1 < len(toks) and W[i + 1]["s"] - W[i]["e"] > 0.3: end = True
    if end: chunks.append([cur[0], cur[-1]]); cur, chars = [], 0
if cur: chunks.append([cur[0], cur[-1]])
disp = [re.sub(r"[\"“”‘’]", "", t) for t in toks]
open(sys.argv[3], "w", encoding="utf8").write("// generated by tools/captions_ts.py\nexport const CAP_TEXT: string[] = " + json.dumps(disp, ensure_ascii=False)
    + ";\nexport const CAPS: [number, number][] = " + json.dumps(chunks) + ";\n")
print(len(chunks), "caption chunks")
