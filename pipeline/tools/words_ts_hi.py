# Hindi-only reels: words.json -> words.ts with Devanagari tokens, plus LINES (index of each script line's first word)
# usage: words_ts_hi.py words.json lines.txt words.ts [end_s]
import json, re, sys
W = json.load(open(sys.argv[1])); L = [l for l in open(sys.argv[2]).read().splitlines() if l.strip()]
end = float(sys.argv[4]) if len(sys.argv) > 4 else 0.0
clean = lambda s: re.sub(r"[,.!?:;।…\"'()‘’“”]", "", s).strip()
tok = lambda l: [t for t in (clean(x) for x in l.split()) if t]
rows = [[clean(w["w"]), round(w["s"], 3), round(w["e"], 3)] for w in W]
counts = [len(tok(l)) for l in L]; assert sum(counts) == len(rows), (sum(counts), len(rows))
starts, acc = [], 0
for c in counts: starts.append(acc); acc += c
for i, s in enumerate(starts): assert rows[s][0] == tok(L[i])[0], (i, rows[s][0], tok(L[i])[0])
open(sys.argv[3], "w").write("// generated by tools/words_ts_hi.py\nexport const WORDS: [string, number, number][] = " + json.dumps(rows, ensure_ascii=False) + ";\nexport const LINES: number[] = " + json.dumps(starts) + ";\nexport const END_AT = " + str(max(end, rows[-1][2])) + ";\n")
for i, s in enumerate(starts): print(i + 1, rows[s][1], rows[s][0])
print(len(rows), "words, END_AT", max(end, rows[-1][2]))
